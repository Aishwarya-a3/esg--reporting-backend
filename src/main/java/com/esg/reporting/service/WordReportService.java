
package com.esg.reporting.service;

import java.io.ByteArrayOutputStream;

import org.apache.poi.xwpf.usermodel.XWPFDocument;
import org.apache.poi.xwpf.usermodel.XWPFParagraph;
import org.apache.poi.xwpf.usermodel.XWPFRun;
import org.apache.poi.xwpf.usermodel.XWPFTable;

import org.springframework.stereotype.Service;

import com.esg.reporting.entity.EsgReport;
import com.esg.reporting.repository.EsgReportRepository;

@Service
public class WordReportService {

    private final EsgReportRepository reportRepository;

    public WordReportService(EsgReportRepository reportRepository) {
        this.reportRepository = reportRepository;
    }

    public byte[] generateReport(Long reportId) throws Exception {

        EsgReport report = reportRepository.findById(reportId)
                .orElseThrow(() ->
                    new IllegalArgumentException("ESG report not found"));

        try (XWPFDocument document = new XWPFDocument();
             ByteArrayOutputStream output = new ByteArrayOutputStream()) {

            XWPFParagraph title = document.createParagraph();
            title.setStyle("Title");

            XWPFRun titleRun = title.createRun();
            titleRun.setText("ESG Sustainability Report");
            titleRun.setBold(true);
            titleRun.setFontSize(18);

            XWPFTable table = document.createTable(5, 2);

            setCell(table, 0, 0, "Field");
            setCell(table, 0, 1, "Value");
            setCell(table, 1, 0, "Report ID");
            setCell(table, 1, 1, String.valueOf(report.getId()));
            setCell(table, 2, 0, "Organization");
            setCell(table, 2, 1, report.getOrganizationName());
            setCell(table, 3, 0, "Reporting Period");
            setCell(table, 3, 1, report.getReportingPeriod());
            setCell(table, 4, 0, "Status");
            setCell(table, 4, 1, report.getStatus());

            XWPFParagraph footer = document.createParagraph();
            footer.createRun().setText(
                    "Generated by the ESG Reporting System");

            document.write(output);
            return output.toByteArray();
        }
    }

    private void setCell(XWPFTable table, int row, int column,
                         String value) {
        table.getRow(row).getCell(column).setText(
                value == null ? "" : value);
    }
}
