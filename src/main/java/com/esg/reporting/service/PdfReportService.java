
package com.esg.reporting.service;

import java.io.ByteArrayOutputStream;

import org.springframework.stereotype.Service;

import com.esg.reporting.entity.EsgReport;
import com.esg.reporting.repository.EsgReportRepository;
import com.lowagie.text.Document;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;

@Service
public class PdfReportService {

    private final EsgReportRepository reportRepository;

    public PdfReportService(EsgReportRepository reportRepository) {
        this.reportRepository = reportRepository;
    }

    public byte[] generateReport(Long reportId) throws Exception {
        EsgReport report = reportRepository.findById(reportId)
                .orElseThrow(() ->
                    new IllegalArgumentException("ESG report not found"));

        ByteArrayOutputStream output = new ByteArrayOutputStream();
        Document document = new Document();

        PdfWriter.getInstance(document, output);
        document.open();

        Font titleFont = FontFactory.getFont(
                FontFactory.HELVETICA_BOLD, 18);
        document.add(new Paragraph("ESG Sustainability Report", titleFont));
        document.add(new Paragraph(" "));

        PdfPTable table = new PdfPTable(2);
        table.setWidthPercentage(100);

        table.addCell(new Phrase("Field"));
        table.addCell(new Phrase("Value"));

        table.addCell("Report ID");
        table.addCell(String.valueOf(report.getId()));

        table.addCell("Organization");
        table.addCell(report.getOrganizationName());

        table.addCell("Reporting Period");
        table.addCell(report.getReportingPeriod());

        table.addCell("Status");
        table.addCell(report.getStatus());

        table.addCell("Revision");
        table.addCell(String.valueOf(report.getRevisionNumber()));

        document.add(table);
        document.add(new Paragraph(" "));
        document.add(new Paragraph(
                "Generated by the ESG Reporting System"));

        document.close();
        return output.toByteArray();
    }
}
